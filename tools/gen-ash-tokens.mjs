// One source, three outputs: the web page's CSS variables, Android colour/dimension resources, and Kotlin constants.
// node tools/gen-ash-tokens.mjs   (run after editing design/app/tokens.json; the outputs are committed)
// node tools/gen-ash-tokens.mjs --check   writes nothing and exits 1 when a committed output differs from tokens.json
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const t = JSON.parse(readFileSync(join(root, 'design/app/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const stale = [];
const out = (rel, text) => {
  const f = join(root, rel);
  if (check) { if (!existsSync(f) || readFileSync(f, 'utf8') !== text) stale.push(rel); return; }
  mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, text);
};
const camel = (k) => k.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const snake = (k) => k.replace(/-/g, '_');
/** CSS colour (#RRGGBB or rgba(r,g,b,a)) → Android #AARRGGBB. */
function argb(v) {
  v = v.trim();
  let m = v.match(/^#([0-9a-f]{6})$/i);
  if (m) return '#FF' + m[1].toUpperCase();
  m = v.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)$/i);
  if (!m) throw Error('unsupported colour ' + v);
  const a = Math.round((m[4] === undefined ? 1 : +m[4]) * 255);
  return '#' + [a, +m[1], +m[2], +m[3]].map((n) => n.toString(16).padStart(2, '0')).join('').toUpperCase();
}
const head = 'Generated by tools/gen-ash-tokens.mjs from design/app/tokens.json. Do not edit by hand.';
const colors = Object.entries(t.color);

// 1. Web
const vars = (mode) => colors.map(([k, v]) => `  --${k}:${v[mode]};`).join('\n');
out('packages/web/ash-tokens.css', `/* ${head} */
:root{
  color-scheme:light;
${vars('light')}
  --shadow-1:${t.shadow.card.light};
  --shadow-2:${t.shadow.sheet.light};
  --ease:${t.motion.easing};
}
@media (prefers-color-scheme:dark){
  :root{
    color-scheme:dark;
${vars('dark').replace(/^/gm, '  ')}
    --shadow-1:${t.shadow.card.dark};
    --shadow-2:${t.shadow.sheet.dark};
  }
}
`);

// 2. Android resources
const xml = (mode) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${head} -->
<resources>
${colors.map(([k, v]) => `    <color name="ash_${snake(k)}">${argb(v[mode])}</color>`).join('\n')}
</resources>
`;
out('android/app/src/main/res/values/ash_colors.xml', xml('light'));
out('android/app/src/main/res/values-night/ash_colors.xml', xml('dark'));
const dim = [];
for (const [k, v] of Object.entries(t.space)) dim.push(`    <dimen name="ash_space_${k}">${v}dp</dimen>`);
for (const [k, v] of Object.entries(t.radius)) if (typeof v === 'number') dim.push(`    <dimen name="ash_radius_${k}">${v === 999 ? 999 : v}dp</dimen>`);
for (const [k, v] of Object.entries(t.size)) dim.push(`    <dimen name="ash_size_${k}">${v}dp</dimen>`);
for (const [k, v] of Object.entries(t.type)) dim.push(`    <dimen name="ash_text_${k}">${v.size}sp</dimen>`);
out('android/app/src/main/res/values/ash_dimens.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- ${head} -->
<resources>
${dim.join('\n')}
</resources>
`);

// 3. Kotlin
const kc = (v) => `0x${argb(v).slice(1)}.toInt()`;
const pal = (mode) => colors.map(([k, v]) => `        ${camel(k)} = ${kc(v[mode])},`).join('\n');
const typeRows = Object.entries(t.type).map(([k, v]) =>
  `        val ${k} = AshType(${v.size}f, ${v.line}f, ${v.weight}${v.color ? `, Role.${camel(v.color).toUpperCase().replace(/(\d)/, '_$1')}` : ', null'})`).join('\n');
const roles = [...new Set(Object.values(t.type).map((v) => v.color).filter(Boolean))];
out('android/app/src/main/java/ai/ash/ui/design/AshTokens.kt', `// ${head}
package ai.ash.ui.design

/** Every colour the app uses, for one theme. Pick with [AshTokens.palette]. */
data class AshPalette(
${colors.map(([k]) => `    val ${camel(k)}: Int,`).join('\n')}
)

/** Which palette colour a text style uses by default. */
enum class Role { ${roles.map((r) => camel(r).toUpperCase().replace(/(\d)/, '_$1')).join(', ')} }

data class AshType(val sizeSp: Float, val lineSp: Float, val weight: Int, val role: Role?)

object AshTokens {
    val light = AshPalette(
${pal('light')}
    )
    val dark = AshPalette(
${pal('dark')}
    )
    fun palette(night: Boolean) = if (night) dark else light

    object Type {
${typeRows}
    }
    object Space { ${Object.entries(t.space).map(([k, v]) => `const val ${k} = ${v}`).join('; ')} }
    object Radius { ${Object.entries(t.radius).filter(([, v]) => typeof v === 'number').map(([k, v]) => `const val ${k} = ${v}`).join('; ')}; const val avatarFraction = 0.32f }
    object Size { ${Object.entries(t.size).map(([k, v]) => `const val ${k} = ${Number.isInteger(v) ? v : v + 'f'}`).join('; ')} }
    object Motion {
        const val message = ${t.motion.message}L; const val sheet = ${t.motion.sheet}L; const val cardResolve = ${t.motion.cardResolve}L
        const val breathe = ${t.motion.breathe}L; const val ring = ${t.motion.ring}L; const val spinner = ${t.motion.spinner}L
        /** ${t.motion.easing} */
        fun easing() = android.view.animation.PathInterpolator(0.32f, 0.72f, 0f, 1f)
    }
}
`);
if (check && stale.length) { console.error('stale generated files (run: node tools/gen-ash-tokens.mjs):\n' + stale.map((f) => '  ' + f).join('\n')); process.exit(1); }
console.log(check ? 'up to date' : 'ok', colors.length, 'colours');
