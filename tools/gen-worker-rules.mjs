#!/usr/bin/env node
// Keep the worker compiler's bundled rule text byte-for-byte aligned with its source module.
import { readFileSync, writeFileSync as writeFile, renameSync } from "node:fs";
const writeFileSync = (path, text) => { const temp = `${path}.${process.pid}.tmp`; writeFile(temp, text); renameSync(temp, path); };
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../packages/core/src");
const source = readFileSync(join(root, "prompts/rules/data-not-instructions.md"), "utf8");
const mainRuleNames = ["voice", "reactions", "self-files", "data-not-instructions", "gate", "approvals", "env", "tools", "devices", "phone", "browser", "media", "reminders", "senses", "widgets", "apps", "agents", "delegate", "pulse", "persona", "daily"];
// Declared agents (not the one the owner talks with) get their own brief plus these.
const agentRuleNames = ["env", "agents", "data-not-instructions", "approvals"];
const rules = (names) => names.map((name) => readFileSync(join(root, "prompts/rules", `${name}.md`), "utf8").trim()).join("\n\n");
const mainRules = rules(mainRuleNames);
const agentRules = rules(agentRuleNames);
writeFileSync(join(root, "workers/rules.generated.ts"),
  `// GENERATED by tools/gen-worker-rules.mjs from prompts/rules/*.md.\n` +
  `export const DATA_NOT_INSTRUCTIONS_RULE: string = ${JSON.stringify(source)};\n` +
  `export const MAIN_RULES: string = ${JSON.stringify(mainRules)};\n` +
  `export const AGENT_RULES: string = ${JSON.stringify(agentRules)};\n`);

const names = ["extract", "verify_claims", "reconcile", "verify_plan", "proactive", "opener"];
const steps = Object.fromEntries(names.map((name) => {
  const content = readFileSync(join(root, "prompts/workers", `${name}.md`), "utf8").trim();
  if (!content) throw new Error(`empty worker step: ${name}`);
  return [name, content];
}));
writeFileSync(join(root, "workers/steps.generated.ts"),
  `// GENERATED by tools/gen-worker-rules.mjs from prompts/workers/*.md.\n` +
  `import type { WorkerName } from "../../../sdk/src/api";\n` +
  `export const WORKER_STEP_TEXT: Record<WorkerName, string> = ${JSON.stringify(steps, null, 2)};\n`);
