// The designer's line icons (design/app/icons/*.svg) as a module the page can draw: icon("chev", "i-s") gives <svg class="i i-s">.
// node tools/gen-ash-icons.mjs          (run after the icon set changes; the output is committed)
// node tools/gen-ash-icons.mjs --check  writes nothing and exits 1 when the committed module differs from the svg files
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const dir = join(root, 'design/app/icons');
const target = 'packages/web/js/ash-icons.js';
const shapes = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg') && f !== 'app-icon.svg').sort()) {
  const svg = readFileSync(join(dir, file), 'utf8');
  const list = [];
  for (const m of svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/>/g)) {
    const attrs = Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
    list.push([m[1], attrs]);
  }
  if (!list.length) throw Error('no shapes in ' + file);
  shapes[file.slice(0, -4)] = list;
}
const text = `// Generated by tools/gen-ash-icons.mjs from design/app/icons/*.svg. Do not edit by hand.
const NS = "http://www.w3.org/2000/svg";

/** Every icon as its drawing instructions: [tag, attributes] on a 24 grid, stroke 1.8, round caps. */
export const ICON_SHAPES = {
${Object.entries(shapes).map(([name, list]) => `  ${/^[a-z]+$/.test(name) ? name : JSON.stringify(name)}: ${JSON.stringify(list)},`).join('\n')}
};

/** An <svg class="i …"> for [name] (see ash-ui.css .i, .i-s, .i-xs, .i-l); it takes the text colour. */
export function icon(name, className = "") {
  const shapes = ICON_SHAPES[name];
  if (!shapes) throw new Error("no icon " + name);
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("class", className ? "i " + className : "i");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("aria-hidden", "true");
  for (const [tag, attrs] of shapes) {
    const node = document.createElementNS(NS, tag);
    for (const [key, value] of Object.entries(attrs)) node.setAttribute(key, value);
    svg.append(node);
  }
  return svg;
}
`;
const file = join(root, target);
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error('stale generated file (run: node tools/gen-ash-icons.mjs):\n  ' + target); process.exit(1); }
  console.log('up to date', Object.keys(shapes).length, 'icons');
} else { writeFileSync(file, text); console.log('ok', Object.keys(shapes).length, 'icons'); }
